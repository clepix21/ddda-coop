"""Builds the GOG address table for the addresses the mod uses (used.txt from list_addrs.py), from
insn_map.tsv (code) and ref_map.tsv (globals, vtables, IAT slots). Writes the C++ table and a report.
Usage: python -I make_table.py <used.txt> <out .h>"""
import bisect, sys
insn = {}
for l in open('insn_map.tsv'):
    a, b = l.split(); insn[int(a, 16)] = int(b, 16)
ref = {}
for l in open('ref_map.tsv'):
    a, b, n, t = l.split(); ref[int(a, 16)] = (int(b, 16), int(n), int(t))
keys = sorted(ref)
byte = {}  # match.py: a unique byte pattern (addresses and rel32 masked)
for l in open('map.tsv'):
    a, sec, k, g, _ = l.rstrip('\n').split('\t')
    if k == 'found':
        byte[int(a, 16)] = int(g, 16)
KEEP = {0x00401000, 0x01700000, 0x01300000, 0x00FFFFFF, 0x01621000, 0x019AB1E0, 0x018C0000, 0x01A00000,
        0x018FA400, 0x018FA600, 0x00434444}
# by hand: loads of the keyboard / mouse globals in the action helpers, paired in order (18 loads in
# 0x0040D160..0x0040D9A0 on both builds, same globals and registers, 2026-11-15)
MANUAL = {0x0040D22A: 0x0040D12D, 0x0040D230: 0x0040D133, 0x0040D568: 0x0040D46A, 0x0040D898: 0x0040D7BD,
          0x0040D89E: 0x0040D7C3}
# not through the table: the save owner check differs (save_guard.cpp has both builds' patch)
SKIP = {0x0040FA31}
rows, bad = [], []
for l in open(sys.argv[1]):
    v = int(l.split()[0], 16)
    if v in KEEP:
        continue
    how = None
    if v in SKIP:
        continue
    if v in MANUAL:
        g, how = MANUAL[v], 'by hand (ordered loads)'
    elif v in insn:
        g, how = insn[v], 'insn'
    elif v in byte:
        g, how = byte[v], 'bytes'
    elif v in ref and ref[v][1] * 2 > ref[v][2]:
        g, how = ref[v][0], f'ref {ref[v][1]}/{ref[v][2]}'
    else:
        # a global not referenced as such (or a range bound): from the nearest referenced neighbours
        i = bisect.bisect_left(keys, v)
        near = [k for k in keys[max(0, i - 3):i + 3] if abs(k - v) < 0x40 and ref[k][1] * 2 > ref[k][2]]
        ds = {ref[k][0] - k for k in near}
        if len(ds) == 1 and near and v >= 0x01000000:  # data only: code goes by bytes
            g, how = v + ds.pop(), 'near ' + ','.join(f'{k:08X}' for k in near)
    if how == 'insn' and v in byte and byte[v] != g:
        how += f' (bytes say {byte[v]:08X}!)'
    if how is None:
        bad.append(l.strip())
        continue
    rows.append((v, g, how, l.split()[1:]))
with open(sys.argv[2], 'w', newline='\n') as f:
    f.write('// Generated by coop-test/gog/make_table.py from Ghidra exports of both exes (match_funcs.py):\n')
    f.write('// every DDDA.exe address the mod uses, Steam build 2364871 -> GOG build (TimeDateStamp 0x5936ABAB).\n')
    f.write('#pragma once\n#include <cstdint>\n\nnamespace game {\nstruct VaPair {\n    uint32_t steam, gog;\n};\n')
    f.write('inline constexpr VaPair kGogMap[] = {\n')
    for v, g, how, w in rows:
        f.write(f'    {{0x{v:08X}, 0x{g:08X}}}, // {how}; {" ".join(w[:2])}\n')
    f.write('};\n} // namespace game\n')
print(len(rows), 'mapped,', len(bad), 'missing')
for b in bad: print('MISSING', b)
