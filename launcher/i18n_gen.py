"""Writes launcher/i18n.h from launcher/i18n_table.py (the launcher's texts in five languages).
Usage: python -I launcher/i18n_gen.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)  # run with -I
from i18n_table import KEYWORDS, LANG_CODES, LANG_NAMES, T  # noqa: E402


def key(fr):
    """The French text as written between the quotes in launcher.cpp (an r-string keeps \\' as two chars)."""
    fr = fr.replace("\\'", "'")
    return re.sub(r'\\u([0-9A-Fa-f]{4})', lambda m: chr(int(m.group(1), 16)), fr)  # • as written or as the character


def lit(text):
    """A plain text as a C++ wide literal."""
    out = text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    return 'L"' + out + '"'


def main():
    seen = set()
    rows = []
    for row in T:
        assert len(row) == 5, row[0]
        k = key(row[0])
        assert k not in seen, 'twice: ' + k
        seen.add(k)
        rows.append('    {{L"{}", {}}},'.format(k, ', '.join(lit(t) for t in row[1:])))
    kw = []
    for code in ('en', 'it', 'de', 'es'):
        for kind, words in zip((3, 2, 1), KEYWORDS[code]):
            kw.append('    {{{}, {}, {{{}}}}},'.format(LANG_CODES.index(code.upper()), kind, ', '.join(lit(w) for w in words) + ', nullptr'))
    h = '''// Generated by launcher/i18n_gen.py from launcher/i18n_table.py: edit the table, not this file.
// The launcher's texts in French (the source, as written in launcher.cpp), English, Italian, German, Spanish.
#pragma once
#include <string>
#include <unordered_map>

enum Lang { LANG_FR, LANG_EN, LANG_IT, LANG_DE, LANG_ES, LANG_COUNT };
inline int g_lang = LANG_FR; // set from DDDA-Coop.ini (lang=) or Windows' language before the window is made
const wchar_t *const kLangNames[LANG_COUNT] = {%s};
const wchar_t *const kLangCodes[LANG_COUNT] = {%s};

struct TrRow {
    const wchar_t *t[LANG_COUNT];
};
inline const TrRow kTr[] = {
%s
};

// The text in the chosen language; the French one when the table has no row for it.
inline const wchar_t *tr(const wchar_t *fr)
{
    if (g_lang == LANG_FR || !fr)
        return fr;
    static std::unordered_map<std::wstring, const TrRow *> rows;
    if (rows.empty())
        for (const TrRow &r : kTr)
            rows[r.t[0]] = &r;
    auto it = rows.find(fr);
    return it == rows.end() ? fr : it->second->t[g_lang];
}

// The plural form for a count: French puts 0 and 1 in the singular, the other four only 1.
inline bool plural(long long n)
{
    return g_lang == LANG_FR ? n > 1 : n != 1;
}

// Words that mark an event's kind (3 error, 2 warning, 1 good) in each translation (event_kind).
struct TrKeywords {
    int lang, kind;
    const wchar_t *words[16];
};
inline const TrKeywords kTrKeywords[] = {
%s
};
''' % (', '.join(lit(n) for n in LANG_NAMES), ', '.join(lit(c) for c in LANG_CODES), '\n'.join(rows), '\n'.join(kw))
    open(os.path.join(HERE, 'i18n.h'), 'w', encoding='utf-8', newline='\n').write(h)
    print(len(rows), 'texts')


if __name__ == '__main__':
    main()
